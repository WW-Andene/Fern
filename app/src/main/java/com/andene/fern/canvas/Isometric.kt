package com.andene.fern.canvas

import kotlin.math.round
import kotlin.math.sqrt

/*
 * Isometric drawing (roadmap item 142): the isometric paper's lattice, and the three planes of
 * an isometric cube that shapes and selections can be drawn or placed on, as in Affinity
 * Designer's isometric panel. Uses the drawing convention of true lengths along the axes
 * (no 0.816 foreshortening), so the lattice spacing measures along every axis.
 */

private val COS_30 = sqrt(3.0) / 2

/**
 * A face of the isometric cube, as the screen directions its x and y axes run in (y down):
 * the top face's axes both slope 30°, the left and right faces keep one 30° axis and run their
 * other one straight down.
 */
enum class IsometricPlane(val xAxis: WorldPoint, val yAxis: WorldPoint) {
    TOP(WorldPoint(COS_30, 0.5), WorldPoint(-COS_30, 0.5)),
    LEFT(WorldPoint(COS_30, 0.5), WorldPoint(0.0, 1.0)),
    RIGHT(WorldPoint(COS_30, -0.5), WorldPoint(0.0, 1.0));

    /** [point], given in the plane's own flat coordinates relative to [origin], placed on the plane. */
    fun toScreenPlane(point: WorldPoint, origin: WorldPoint): WorldPoint {
        val dx = point.x - origin.x
        val dy = point.y - origin.y
        return WorldPoint(origin.x + xAxis.x * dx + yAxis.x * dy, origin.y + xAxis.y * dx + yAxis.y * dy)
    }

    /** The inverse of [toScreenPlane]: where a point on the plane lies in the plane's flat coordinates. */
    fun toFlat(point: WorldPoint, origin: WorldPoint): WorldPoint {
        val dx = point.x - origin.x
        val dy = point.y - origin.y
        val det = xAxis.x * yAxis.y - yAxis.x * xAxis.y
        return WorldPoint(origin.x + (yAxis.y * dx - yAxis.x * dy) / det, origin.y + (xAxis.x * dy - xAxis.y * dx) / det)
    }
}

/**
 * The shape [kind] dragged from [start] to [end] on [plane]: drawn flat between the drag's
 * flat-coordinate ends, then laid onto the plane, so a rectangle becomes a rhombus face and an
 * ellipse an isometric circle. Without a plane, the shape as usual.
 */
fun shapeOnPlane(kind: ShapeKind, start: WorldPoint, end: WorldPoint, plane: IsometricPlane?): List<WorldPoint> {
    if (plane == null) return generateShapePoints(kind, start, end)
    return generateShapePoints(kind, start, plane.toFlat(end, start)).map { plane.toScreenPlane(it, start) }
}

/**
 * The isometric lattice point at [point] rounded in lattice coordinates (nearest or close to
 * it), for lattice [spacing]: the points where the vertical lines and the two 30° families
 * meet, generated by (cos30, 1/2) and (0, 1) times [spacing].
 */
fun snappedToIsometric(point: WorldPoint, spacing: Double): WorldPoint {
    val i = round(point.x / (spacing * COS_30))
    val j = round((point.y - i * spacing / 2) / spacing)
    return WorldPoint(i * spacing * COS_30, j * spacing + i * spacing / 2)
}

/** The horizontal period of the isometric lattice for [spacing]: an x shift by it (and none in y) maps the lattice onto itself. */
fun isometricPeriodX(spacing: Double): Double = 2 * spacing * COS_30
